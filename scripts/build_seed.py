"""Builds supabase/seed.sql from scripts/questions.json.
Run:  python3 scripts/build_seed.py
Edit questions.json (the single source of truth), re-run, then paste the
generated seed.sql into the Supabase SQL editor. Safe to re-run: existing
questions are updated in place and old ones are deactivated, never deleted,
so collected responses are never lost.
"""
import json, re, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
D = json.loads((root / "scripts" / "questions.json").read_text(encoding="utf-8"))
WORKING = ["Employed full-time", "Employed part-time", "Self-employed"]

def q(s):  # SQL string literal
    return "NULL" if s is None else "'" + str(s).replace("'", "''") + "'"

def j(o):
    return "NULL" if o is None else q(json.dumps(o, ensure_ascii=False))

def expand(opts):
    if isinstance(opts, str):
        opts = ["@" + opts]
    out = []
    for o in opts:
        out += D["scales"][o[1:]] if o.startswith("@") else [o]
    return out

rows = []  # (slug, key, section, type, prompt_tamil, prompt_english, options, condition, order)

n = 0
for section, items in D["interview"]:
    for text in items:
        n += 1
        rows.append(("interview", f"int_{n:02d}", section, "audio", text, None, None, None, n))
assert n == 50, n

n = 0
for section, items in D["gss"]:
    for code, text, opts in items:
        n += 1
        slug = re.sub(r"[^a-z0-9]+", "_", code.lower()).strip("_")
        cond = {"field": "work_status", "in": WORKING} if code in D["working_only"] else None
        rows.append(("gss", f"gss_q{n:02d}_{slug}", section, "single_choice", None, text, expand(opts), cond, n))
assert n == 42, n

n = 0
for trait, items in D["bfi"]:
    for i, (text, rev) in enumerate(items, 1):
        n += 1
        rows.append(("bfi", f"bfi_{trait[0].lower()}{i}{'_r' if rev else ''}", trait, "likert5", None, text, D["bfi_scale"], None, n))
assert n == 44, n

for n, g in enumerate(D["games"], 1):
    rows.append(("behavioral_games", g["key"], g["section"], g["type"], None, g["text"], g["options"], None, n))

values = ",\n".join(
    f"  ({q(s)}, {q(k)}, {q(sec)}, {q(t)}, {q(pt)}, {q(pe)}, {j(o)}, {j(c)}, {n})"
    for s, k, sec, t, pt, pe, o, c, n in rows
)
keys = ", ".join(q(r[1]) for r in rows)

sql = f"""-- GENERATED by scripts/build_seed.py from scripts/questions.json. Do not edit by hand.
-- Run AFTER schema.sql. Safe to re-run (updates in place, deactivates old questions).

-- Migration for projects created from the earlier schema:
alter table questions alter column prompt_tamil drop not null;
alter table questions add column if not exists condition jsonb;

insert into instruments (slug, name_tamil, name_english, kind, order_index, is_active) values
  ('interview', 'ஒலிப்பேட்டு நேர்காணல்', 'Audio interview (5 batches x 10)', 'audio_interview', 1, true),
  ('gss', 'சமூகக் கணக்கெடுப்பு', 'General Social Survey (GSS)', 'survey', 2, true),
  ('bfi', 'ஆளுமைக் கணக்கெடுப்பு', 'Personality (BFI-44)', 'survey', 3, true),
  ('behavioral_games', 'நடத்தை விளையாட்டுகள்', 'Behavioral / economic games', 'survey', 4, true)
on conflict (slug) do update set name_tamil = excluded.name_tamil, name_english = excluded.name_english,
  kind = excluded.kind, order_index = excluded.order_index, is_active = true;

-- the old separate economic-games section is merged into behavioral_games
update instruments set is_active = false where slug = 'econ_games';

insert into questions (instrument_id, question_key, section, type, prompt_tamil, prompt_english, options, condition, order_index, is_active)
select i.id, v.k, v.sec, v.t, v.pt, v.pe, v.o::jsonb, v.c::jsonb, v.n, true
from (values
{values}
) as v(slug, k, sec, t, pt, pe, o, c, n)
join instruments i on i.slug = v.slug
on conflict (instrument_id, question_key) do update set
  section = excluded.section, type = excluded.type, prompt_tamil = excluded.prompt_tamil,
  prompt_english = excluded.prompt_english, options = excluded.options,
  condition = excluded.condition, order_index = excluded.order_index, is_active = true;

-- deactivate older placeholder questions (kept in the table so no data is lost)
update questions set is_active = false where question_key not in ({keys});
"""
(root / "supabase" / "seed.sql").write_text(sql, encoding="utf-8")
print(f"seed.sql written: {len(rows)} questions "
      f"(interview 50, gss 42, bfi 44, games {len(D['games'])})")
